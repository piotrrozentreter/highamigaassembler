def loads(text: str) -> MetadataManager:
    """Rebuild a MetadataManager from `.hasmeta` source."""
    manager = MetadataManager()
    in_layout = False

    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(";"):
            continue

        header = _DEFINE_WINDOW_RE.match(line)
        if header:
            _apply_window(manager.window, _parse_attrs(header.group(1)))
            continue

        if line.startswith("BEGIN_GUI_LAYOUT"):
            in_layout = True
            continue
        if line.startswith("END_GUI_LAYOUT"):
            in_layout = False
            continue

        if in_layout:
            body = _ADD_CONTROL_RE.search(line)
            if body:
                _apply_control(manager, _parse_attrs(body.group(1)))

    return manager


def load(path: Path) -> MetadataManager:
    return loads(Path(path).read_text(encoding="utf-8"))


def _apply_window(win: WindowSpec, attrs: Dict[str, str]) -> None:
    win.caption = attrs.get("CAPTION", win.caption)
    win.width = _as_int(attrs.get("WIDTH", ""), win.width)
    win.height = _as_int(attrs.get("HEIGHT", ""), win.height)
    win.left = _as_int(attrs.get("LEFT", ""), win.left)
    win.top = _as_int(attrs.get("TOP", ""), win.top)
    if "FLAGS" in attrs:
        flags = _as_int(attrs["FLAGS"], 0)
        win.sizeable = bool(flags & 0x00000001)
        win.dragbar = bool(flags & 0x00000002)
        win.depth_gadget = bool(flags & 0x00000004)
        win.close_gadget = bool(flags & 0x00000008)
        win.activate = bool(flags & 0x00001000)


def _apply_control(manager: MetadataManager, attrs: Dict[str, str]) -> None:
    try:
        kind = ControlType(attrs.get("TYPE", "").upper())
    except ValueError:
        return
    caption = attrs.get("TEXT") or attrs.get("CAPT") or attrs.get("ITEXT") or ""
    manager.add(
        kind=kind,
        x=_as_int(attrs.get("X", ""), 0),
        y=_as_int(attrs.get("Y", ""), 0),
        w=_as_int(attrs.get("W", ""), 0) or None,
        h=_as_int(attrs.get("H", ""), 0) or None,
        caption=caption,
        name=attrs.get("NAME") or None,
        maxlen=_as_int(attrs.get("MAXLEN", ""), 32),
        checked=bool(_as_int(attrs.get("CHECKED", ""), 0)),
        items=_decode_items(attrs),
        selected=_as_int(attrs.get("SELECTED", ""), 0),
        asset_path=attrs.get("ASSET", ""),
        bitmap_colors=_as_int(attrs.get("COLORS", ""), 2),
        action_id=_as_int(attrs.get("ID", ""), 0) or None,
    )


def _decode_items(attrs: Dict[str, str]) -> List[str]:
    payload = attrs.get("ITEMS64", "")
    if payload:
        try:
            return base64.b64decode(payload.encode("ascii")).decode("utf-8").split("\0")
        except (UnicodeDecodeError, ValueError):
            return []
    return [item for item in attrs.get("ITEMS", "").split("|") if item]
